function exportHighOrder(filePath, result, notes)
%EXPORTHIGHORDER Shot 高次補正の評価（alignest.shotHighOrder の結果）を Excel ファイル（.xlsx）に書き出す。
%   alignest.exportHighOrder(filePath, result)
%   alignest.exportHighOrder(filePath, result, notes)   % notes：「説明」シートに足す行（[項目, 内容] の2列の文字列）
%   シート：「説明」（作成日時・補正の式と回帰の設定・画面のメッセージ・notes）、「補正の評価」（Wafer・軸ごとの |平均|+3σ）、
%   「補正値」（k パラメータなどの係数）、「項とVIF」（補正の式の項・使ったか・VIF）、「点ごとの値」（値・補正量・残差・重み）。
arguments
    filePath (1, 1) string
    result struct
    notes (:, 2) string = strings(0, 2)
end
[~, ~, extension] = fileparts(filePath);
if ~strcmpi(extension, ".xlsx")
    error('alignest:exportType', '書き出し先は .xlsx にしてください: %s', filePath);
end
if isfile(filePath)
    try
        delete(filePath);
    catch err
        error('alignest:exportLocked', '「%s」を置き換えられません（Excel で開いていないか確かめてください）。理由: %s', ...
            filePath, err.message);
    end
end
options = result.options;
items = ["作成日時"; "補正"; "補正の式"; "回帰"; "評価"; "画面のメッセージ"; notes(:, 1)];
values = [string(datetime('now', 'Format', 'yyyy/MM/dd HH:mm:ss')); result.description; ...
    "Overlay 計測ルールの Shot 高次補正の式（" + upper(options.maker) + "）。x・y は Shot 内の座標 [mm]（Shot 中心が原点）。" + ...
    "dx の式は X の値、dy の式は Y の値に当てはめる。係数は mm の座標での値（nm/mm^次数）。"; ...
    "列（項）を平均0・標準偏差1にそろえてから解く。L2 正則化は高次項（2次以上）だけにかける。Huber・LAD は重みを" + ...
    "変えながら解き直す（尺度は残差の MAD × 1.4826）。"; ...
    "|平均|+3σ は、高次補正と1次（k1〜k6）だけの補正の両方ができた点で比べる。1次だけの補正にも同じ損失関数と" + ...
    "Wafer 成分を使う。1点抜きの予測の誤差は、点を1つずつ抜いて求め直した補正で抜いた点を予測したときの誤差" + ...
    "（e/(1−h)。Huber・LAD は最後の重みのままとした近似）。"; strjoin(result.messages, " "); notes(:, 2)];
writetable(table(items, values, 'VariableNames', ["項目", "内容"]), filePath, 'Sheet', '説明');
summary = result.summary;
writetable(table(summary.wafer, summary.axis, summary.before, summary.linear, summary.highOrder, summary.improvement, ...
    summary.looLinear, summary.looHighOrder, summary.n, summary.nCorrected, summary.nPredicted, summary.shots, ...
    summary.skipped, summary.downweighted, summary.rmsHighOrder, 'VariableNames', ["Wafer", "軸", ...
    "補正前の|平均|+3σ[nm]", "1次だけで補正した残差の|平均|+3σ[nm]", "高次補正の残差の|平均|+3σ[nm]", ...
    "1次だけからの改善[nm]", "1次だけの予測の誤差(1点抜き)の|平均|+3σ[nm]", "高次補正の予測の誤差(1点抜き)の|平均|+3σ[nm]", ...
    "点の数", "比べた点の数", "予測の誤差を比べた点の数", "Shot の数", "補正しなかった組の数", "重みを下げた点の数", ...
    "高次補正の残差のRMS[nm]"]), filePath, 'Sheet', '補正の評価');
coefficients = result.coefficients;
writetable(table(coefficients.wafer, coefficients.shotNo, coefficients.axis, coefficients.component, coefficients.k, ...
    coefficients.term, coefficients.value, coefficients.unit, coefficients.note, 'VariableNames', ["Wafer", "shotNo", ...
    "式", "成分", "k", "項", "補正値(係数)", "単位", "メモ"]), filePath, 'Sheet', '補正値');
terms = result.terms;
writetable(table(terms.axis, terms.k, terms.term, terms.order, terms.used, terms.protected, terms.vifAll, ...
    terms.vifUsed, terms.vifRemoved, terms.removalOrder, 'VariableNames', ["式", "k", "項", "次数", "使う", ...
    "外さない項(k1〜k6)", "VIF(式のすべての項)", "VIF(使う項)", "VIFで選ぶと外れる項のVIF", "外れる順番"]), ...
    filePath, 'Sheet', '項とVIF');
points = result.points;
writetable(table(points.wafer, points.source, points.name, points.shotNo, points.x, points.y, points.localX, ...
    points.localY, points.valueX, points.valueY, points.correctionX, points.correctionY, points.residualX, ...
    points.residualY, points.linearResidualX, points.linearResidualY, points.looX, points.looY, points.weightX, ...
    points.weightY, 'VariableNames', ["Wafer", "点の種類", "名前", "shotNo", "x[mm]", "y[mm]", "Shot内のx[mm]", ...
    "Shot内のy[mm]", "値X[nm]", "値Y[nm]", "補正量X[nm]", "補正量Y[nm]", "残差X[nm]", "残差Y[nm]", ...
    "1次だけの残差X[nm]", "1次だけの残差Y[nm]", "予測の誤差(1点抜き)X[nm]", "予測の誤差(1点抜き)Y[nm]", "重みX", ...
    "重みY"]), filePath, 'Sheet', '点ごとの値');
end
