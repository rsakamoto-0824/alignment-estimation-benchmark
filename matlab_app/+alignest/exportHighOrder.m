function exportHighOrder(filePath, result, notes, comparison, pair)
%EXPORTHIGHORDER Shot 高次補正の評価（alignest.shotHighOrder の結果）を Excel ファイル（.xlsx）に書き出す。
%   alignest.exportHighOrder(filePath, result)
%   alignest.exportHighOrder(filePath, result, notes)   % notes：「説明」シートに足す行（[項目, 内容] の2列の文字列）
%   alignest.exportHighOrder(filePath, result, notes, comparison)   % 補正の比較（alignest.compareHighOrderConditions）も書く
%   alignest.exportHighOrder(..., pair)   % 2つの条件の Shot ごとの比較（shots：alignest.compareHighOrderShots）も書く
%   シート：「説明」（作成日時・補正の式と回帰の設定・外周の Shot・画面のメッセージ・notes）、「補正の評価」（Wafer・軸・
%   範囲（すべて・内周・外周）ごとの |平均|+3σ と高次補正の |残差| の 95% 点・中央値）、「補正の比較」（comparison がある
%   とき）、「Shotごとの比較」（pair があるとき）、「補正値」（Wafer 成分の係数と k パラメータを、Wafer 低次・Wafer 高次・
%   Shot 共通 低次・Shot 共通 高次・Shot 毎 低次・Shot 毎 高次の順に。alignest.highOrderLevels）、「Shotごとの補正値」（1行 =
%   1 Shot に同じ順で横に並べた表。alignest.highOrderShotTable）、「項とVIF」（補正の式の項・使ったか・VIF）、
%   「点ごとの値」（値・k の組・内周か外周か・補正量・残差（高次補正・Shot
%   ごとの1次・Wafer 高次補正だけ・Wafer 高次補正＋Shot 共通補正）・1点抜きの予測の誤差・重み）。
arguments
    filePath (1, 1) string
    result struct
    notes (:, 2) string = strings(0, 2)
    comparison = []
    pair = []
end
[~, ~, extension] = fileparts(filePath);
if ~strcmpi(extension, ".xlsx")
    error('alignest:exportType', '書き出し先は .xlsx にしてください: %s', filePath);
end
if isfile(filePath)
    try
        delete(filePath);
    catch err
        error('alignest:exportLocked', '「%s」を置き換えられません（Excel で開いていないか確かめてください）。理由: %s', ...
            filePath, err.message);
    end
end
options = result.options;
if options.maker == "custom"
    formulaText = "カスタムの式（k1〜k38。Nikon・Canon と同じ番号の付け方で、4次までのすべての項と5次の項の一部）。";
else
    formulaText = "Overlay 計測ルールの Shot 高次補正の式（" + upper(options.maker) + "）。";
end
outerText = sprintf("Shot 中心の半径が %g mm 以上の Shot を外周とする（「補正の評価」の範囲）。", options.outerRadiusMm);
if options.outerMaker ~= "none"
    outerText = outerText + "外周の Shot は外周の式で補正し、k の組を内周と別にした（Wafer 成分は共通）。";
end
items = ["作成日時"; "補正"; "補正の式"; "回帰"; "評価"; "補正値の段階"; "外周の Shot"; "画面のメッセージ"; notes(:, 1)];
values = [string(datetime('now', 'Format', 'yyyy/MM/dd HH:mm:ss')); result.description; ...
    formulaText + "x・y は Shot 内の座標 [mm]（Shot 中心が原点）。" + ...
    "dx の式は X の値、dy の式は Y の値に当てはめる。係数は mm の座標での値（nm/mm^次数）。"; ...
    "列（項）を平均0・標準偏差1にそろえてから解く。正則化（L2・L1）は選んだ次数の項だけにかける。Huber・LAD は重みを" + ...
    "変えながら解き直す（尺度は残差の MAD × 1.4826）。"; ...
    "|平均|+3σ は、高次補正と Shot ごとの1次（k1〜k6 を Shot ごとに求めた補正。同じ損失関数）の両方ができた点で" + ...
    "比べる。|残差| の 95% 点・中央値は、高次補正の残差の大きさ（絶対値）の 95% 点と中央値。外れ値とみなした点は、" + ...
    "Huber・LAD（ロバスト回帰）が残差が大きいため当てはめでの重みを 0.5 未満に下げた点（最小二乗では 0）。Scan 方向ごと・" + ...
    "行の偶奇ごとのときは、k を組ごとに、Wafer 成分を Wafer で共通にして一緒に求める。点の数が最も少ない k の組で" + ...
    "求められない項の扱いは「補正」の説明（初めの設定は、k の小さい順に決められる項だけを全体で使う。画面のメッセージ）。"; ...
    levelText(result.options); outerText; strjoin(result.messages, " "); ...
    notes(:, 2)];
writetable(table(items, values, 'VariableNames', ["項目", "内容"]), filePath, 'Sheet', '説明');
summary = [result.summary; result.regionSummary];
[~, waferOrder] = ismember(summary.wafer, unique(result.summary.wafer, 'stable'));
[~, regionOrder] = ismember(summary.region, ["すべて", "内周", "外周"]);
[~, order] = sortrows([summary.axis == "Y", waferOrder, regionOrder]);
summary = summary(order, :);
writetable(table(summary.wafer, summary.axis, summary.region, summary.before, summary.linear, summary.highOrder, ...
    summary.improvement, summary.highOrderP95, summary.highOrderMedian, summary.n, summary.nCorrected, summary.shots, ...
    summary.kSets, summary.skipped, summary.outliers, summary.rmsHighOrder, 'VariableNames', ["Wafer", "軸", "範囲", ...
    "補正前の|平均|+3σ[nm]", "Shotごとの1次で補正した残差の|平均|+3σ[nm]", "高次補正の残差の|平均|+3σ[nm]", ...
    "Shotごとの1次からの改善[nm]", "高次補正の|残差|の95%点[nm]", "高次補正の|残差|の中央値[nm]", "点の数", ...
    "比べた点の数", "Shot の数", "kの組の数", "補正しなかった組の数", "外れ値とみなした点の数(ロバスト回帰)", ...
    "高次補正の残差のRMS[nm]"]), filePath, 'Sheet', '補正の評価');
if ~isempty(comparison)
    writetable(table(comparison.label, comparison.axis, comparison.description, comparison.before, ...
        comparison.linear, comparison.highOrder, comparison.improvement, comparison.highOrderP95, ...
        comparison.highOrderMedian, comparison.highOrderInner, comparison.highOrderOuter, comparison.nTerms, ...
        comparison.kSets, comparison.skipped, comparison.nCorrected, comparison.note, 'VariableNames', ["条件", "軸", ...
        "補正の設定", "補正前の|平均|+3σ[nm]", "Shotごとの1次で補正した残差の|平均|+3σ[nm]", ...
        "高次補正の残差の|平均|+3σ[nm]", "Shotごとの1次からの改善[nm]", "高次補正の|残差|の95%点[nm]", ...
        "高次補正の|残差|の中央値[nm]", "内周のShotの高次補正の残差の|平均|+3σ[nm]", ...
        "外周のShotの高次補正の残差の|平均|+3σ[nm]", "項の数", "kの組の数", "補正しなかった組の数", "比べた点の数", ...
        "メモ"]), filePath, 'Sheet', '補正の比較');
end
if ~isempty(pair)
    shots = pair.shots;
    writetable(table(shots.wafer, shots.shotNo, shots.zone, shots.Xc, shots.Yc, shots.nCompared, shots.reference, ...
        shots.other, shots.difference, shots.verdict, shots.outliersReference, shots.outliersOther, ...
        'VariableNames', ["Wafer", "shotNo", "範囲", "Shot中心のx[mm]", "Shot中心のy[mm]", "比べた点の数", ...
        "基準の値[nm]", "比べる条件の値[nm]", "差(基準−比べる条件)[nm]", "判定", "外れ値とみなした点(基準)", ...
        "外れ値とみなした点(比べる条件)"]), filePath, 'Sheet', 'Shotごとの比較');
end
levels = alignest.highOrderLevels(result);
writetable(table(levels.wafer, levels.level, levels.shotNo, levels.group, levels.zone, levels.axis, levels.k, ...
    levels.term, levels.value, levels.unit, levels.note, 'VariableNames', ["Wafer", "段階", "shotNo", "くくり", ...
    "式の範囲", "式", "k", "項", "補正値(係数)", "単位", "メモ"]), filePath, 'Sheet', '補正値');
writetable(alignest.highOrderShotTable(result), filePath, 'Sheet', 'Shotごとの補正値');
terms = result.terms;
writetable(table(terms.zone, terms.axis, terms.k, terms.term, terms.order, terms.used, terms.protected, terms.vifAll, ...
    terms.vifUsed, terms.vifRemoved, terms.removalOrder, 'VariableNames', ["式の範囲", "式", "k", "項", "次数", "使う", ...
    "外さない項(k1〜k6)", "VIF(式のすべての項)", "VIF(使う項)", "VIFで選ぶと外れる項のVIF", "外れる順番"]), ...
    filePath, 'Sheet', '項とVIF');
points = result.points;
writetable(table(points.wafer, points.source, points.name, points.shotNo, points.direction, points.rowParity, ...
    points.group, points.shotRadius, points.zone, points.x, points.y, points.localX, points.localY, points.valueX, ...
    points.valueY, points.correctionX, points.correctionY, points.residualX, points.residualY, points.linearResidualX, ...
    points.linearResidualY, points.waferResidualX, points.waferResidualY, points.commonResidualX, ...
    points.commonResidualY, points.looResidualX, points.looResidualY, points.weightX, points.weightY, 'VariableNames', ["Wafer", "点の種類", "名前", "shotNo", ...
    "Scan方向", "Shot行の奇偶(1=奇数行)", "kの組", "Shot中心の半径[mm]", "範囲", "x[mm]", "y[mm]", "Shot内のx[mm]", ...
    "Shot内のy[mm]", "値X[nm]", "値Y[nm]", ...
    "補正量X[nm]", "補正量Y[nm]", "残差X[nm]", "残差Y[nm]", "Shotごとの1次の残差X[nm]", "Shotごとの1次の残差Y[nm]", ...
    "Wafer高次補正だけの残差X[nm]", "Wafer高次補正だけの残差Y[nm]", "Wafer高次補正+Shot共通補正の残差X[nm]", ...
    "Wafer高次補正+Shot共通補正の残差Y[nm]", "1点抜きの予測の誤差X[nm]", "1点抜きの予測の誤差Y[nm]", "重みX", "重みY"]), ...
    filePath, 'Sheet', '点ごとの値');
end

function text = levelText(options)
% 「補正値」「Shotごとの補正値」の段階の説明
text = "Wafer 低次・高次：Wafer 成分（Shot 中心の座標 Xc・Yc の1次・2次以上の項。定数は Shot 共通の k1・k2 に含む）。" + ...
    "Shot 共通 低次・高次：Wafer 内の Shot で共通の k の k1〜k6・k7 以降";
if options.unit == "shot"
    text = text + "（Wafer 成分と一緒に全 Shot で求めた k）。Shot 毎：Shot ごとの k − Shot 共通の k（足すとその Shot に" + ...
        "当てる k。点が足りず使わない項は − Shot 共通）。";
else
    text = text + "（くくりが Scan 方向ごと・行の偶奇ごとなら、その組の k）。Shot 毎：Shot ごとに求めていないので無し。";
end
text = text + "「Shotごとの補正値」の合計は、その Shot に当てる k（k1・k2 は Wafer 成分の並進も足す）。";
end
