function exportMarkLayouts(filePath, study, notes)
%EXPORTMARKLAYOUTS 「8. Mark配置の最適化」の結果（alignest.markLayoutStudy）を Excel ファイル（.xlsx）に書き出す。
%   alignest.exportMarkLayouts(filePath, study)
%   alignest.exportMarkLayouts(filePath, study, notes)   % notes：「説明」シートに足す行（[項目, 内容] の2列の文字列）
%   シート：「説明」（作成日時・補正の式と回帰・配置の選び方・制御残差を求めた値・メッセージ・notes）、「制御残差」（Mark の
%   数ごと・軸ごとの I 効率と制御残差。最後の2行はすべての候補を計測したとき）、「配置」（Mark の数ごとに計測する Mark の
%   番号・座標。1行 = 1つの Mark）、「候補のMark」（候補の番号・座標・必ず計測するか・値のある Shot の数）、「項とVIF」。
arguments
    filePath (1, 1) string
    study struct
    notes (:, 2) string = strings(0, 2)
end
[~, ~, extension] = fileparts(filePath);
if ~strcmpi(extension, ".xlsx")
    error('alignest:exportType', '書き出し先は .xlsx にしてください: %s', filePath);
end
if isfile(filePath)
    try
        delete(filePath);
    catch err
        error('alignest:exportLocked', '「%s」を置き換えられません（Excel で開いていないか確かめてください）。理由: %s', ...
            filePath, err.message);
    end
end
options = study.options;
valueText = "実測値（制御残差 = 実測値 − 補正量）";
if study.valueSource == "random"
    valueText = sprintf(['乱数の Shot の形 %d 通り（種 %d、0〜5次の項の大きさ %s nm、計測のばらつき %g nm、飛び値 %g%%・%g nm。' ...
        '制御残差 = ばらつき・飛び値を足す前の形 − 補正量）'], study.nShots, options.seed, ...
        strjoin(string(options.orderSigmaNm), "・"), options.noiseNm, options.outlierPercent, options.outlierNm);
end
items = ["作成日時"; "補正の式と回帰"; "使う項の数"; "配置の選び方"; "I 効率"; "制御残差を求めた値"; "Shot・形の数"];
values = [string(datetime('now', 'Format', 'yyyy-MM-dd HH:mm:ss')); options.description; ...
    sprintf("dx %d 項・dy %d 項", study.nTerms(1), study.nTerms(2)); ...
    sprintf(['Mark の数 %d〜%d 点のそれぞれで I 最適計画（dx・dy の式の予測の分散の平均の和が最小。交換法、始め方 %d 通り）。' ...
    '必ず計測する Mark %d 点はどの数にも入れる'], study.counts(1), study.counts(end), options.starts, ...
    nnz(study.candidates.required)); ...
    "すべての候補の Mark（" + height(study.candidates) + " 点）を計測したときを 100% とした、予測の分散の平均の比"; ...
    valueText; string(study.nShots)];
items = [items; repmat("メッセージ", numel(study.messages), 1); notes(:, 1)];
values = [values; study.messages(:); notes(:, 2)];
writetable(table(items, values, 'VariableNames', ["項目", "内容"]), filePath, 'Sheet', '説明');
evaluation = study.evaluation;
if height(evaluation) > 0
    writetable(table(evaluation.layoutType, evaluation.count, evaluation.efficiency, evaluation.axis, evaluation.nShots, ...
        evaluation.skipped, evaluation.meanPlus3Sigma, evaluation.p95, evaluation.median, evaluation.rms, ...
        evaluation.unmeasuredMeanPlus3Sigma, evaluation.unmeasuredP95, evaluation.unmeasuredMedian, ...
        evaluation.unmeasuredRms, 'VariableNames', ["配置", "Markの数", "I効率[%]", "軸", "補正したShot", ...
        "補正しなかったShot", "制御残差|平均|+3σ[nm]", "制御残差95%点[nm]", "制御残差中央値[nm]", "制御残差RMS[nm]", ...
        "計測しなかったMarkの|平均|+3σ[nm]", "計測しなかったMarkの95%点[nm]", "計測しなかったMarkの中央値[nm]", ...
        "計測しなかったMarkのRMS[nm]"]), filePath, 'Sheet', '制御残差');
end
layouts = study.layouts;
candidates = study.candidates;
[markIndex, layoutIndex] = find(layouts.selected);
writetable(table(layouts.counts(layoutIndex), layouts.efficiency(layoutIndex), candidates.no(markIndex), ...
    candidates.xMm(markIndex), candidates.yMm(markIndex), candidates.required(markIndex), 'VariableNames', ...
    ["Markの数", "I効率[%]", "Markの番号", "X[mm]", "Y[mm]", "必ず計測"]), filePath, 'Sheet', '配置');
writetable(table(candidates.no, candidates.xMm, candidates.yMm, candidates.required, candidates.nShots, ...
    'VariableNames', ["Markの番号", "X[mm]", "Y[mm]", "必ず計測", "値のあるShotの数"]), filePath, 'Sheet', '候補のMark');
terms = study.terms;
writetable(table(terms.axis, terms.k, terms.term, terms.order, terms.used, terms.protected, terms.vifAll, terms.vifUsed, ...
    'VariableNames', ["式", "k", "項", "次数", "使う", "外さない項", "VIF（全項）", "VIF（使う項）"]), filePath, ...
    'Sheet', '項とVIF');
end
