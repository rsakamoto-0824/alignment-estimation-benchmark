function columns = highOrderColumns()
%HIGHORDERCOLUMNS Shot 高次補正の入力にする Excel・CSV の項目（「7. Shot高次補正」の「Excel・CSV の列」で、ファイルの列を選ぶ）。
%   columns：構造体の配列。name（Overlay 計測ルールの標準の項目名。alignest.prepareData に渡す名前）・meaning（意味）・
%   required（必ず列を選ぶ項目）・aliases（見出しがこの名前の列も、その項目と推定する。大文字・小文字は区別しない）。
%   値は mm・nm（座標の単位は変換しない）。Wafer が無ければ全行を1枚、shotNo が無ければ座標から番号を付ける、
%   Direction が無ければ「Scan 方向が無いとき」の規則で付ける（規則が「付けない」なら Scan 方向ごとには求められない）、
%   StsX・StsY が無ければ値のある点を有効とする（「1. データの読み込み」と同じ）。
names = ["Wafer", "shotNo", "Direction", "Xmm", "Ymm", "markXmm", "markYmm", "measX", "measY", "StsX", "StsY"];
meanings = ["Wafer の名前（無ければ全行を1枚）", "Shot の番号（無ければ座標から付ける）", ...
    "Scan 方向（1・2。Scan 方向ごとの補正に使う）", "Shot 中心の X 座標 [mm]（Wafer 中心が原点）", ...
    "Shot 中心の Y 座標 [mm]", "Shot 内の X 座標 [mm]（Shot 中心から）", "Shot 内の Y 座標 [mm]", ...
    "X の値（dx）[nm]", "Y の値（dy）[nm]", "X の値の状態（0 = 有効。無ければ値のある点）", ...
    "Y の値の状態（0 = 有効。無ければ値のある点）"];
required = [false, false, false, true, true, true, true, true, true, false, false];
aliases = {["WaferID", "Wafer ID"], ["shot", "ShotNo.", "Shot番号"], ["Scan", "ScanDirection", "Scan方向"], ...
    ["ShotX", "Shot中心X"], ["ShotY", "Shot中心Y"], ["markX", "localX", "Shot内X"], ["markY", "localY", "Shot内Y"], ...
    ["dx", "推定値X[nm]", "valueX"], ["dy", "推定値Y[nm]", "valueY"], strings(1, 0), strings(1, 0)};
columns = struct("name", cellstr(names), "meaning", cellstr(meanings), "required", num2cell(required), ...
    "aliases", aliases);
end
