function columns = rotationColumns()
%ROTATIONCOLUMNS 「8. 計測マップのローテーション」で読み込む Excel・CSV の項目（「Excel・CSV の列」で、ファイルの列を選ぶ）。
%   columns：構造体の配列（alignest.highOrderColumns と同じ形：name・meaning・required・aliases）。Shot 高次補正の項目
%   （Shot 中心・Shot 内の座標・X・Y の値は必須）に、Wafer を分ける・並べるための Operation・EqpId・LotID・DateTime と、
%   Mark 番号を足したもの。座標は mm、値は nm のまま（変換しない）。選ばなかったファイルの数値の列は、目的変数に選べる。
base = alignest.highOrderColumns();
extra = struct("name", {'Operation', 'EqpId', 'LotID', 'DateTime', 'markNo'}, ...
    "meaning", {'工程名（対象を Operation ごとに分ける）', '装置ID（対象を装置ごとに分ける）', ...
    'ロットID（ローテーションの Lot。FB の並び順にも使う）', '測定日時（FB の並び順。古い Wafer から FB 側）', ...
    'Shot 内の Mark 番号（無ければ Shot 内の座標から付ける）'}, ...
    "required", {false, false, false, false, false}, ...
    "aliases", {["工程", "Process"], ["装置", "Tool", "EQP"], ["Lot", "Lot ID", "ロット"], ["Date", "日時", "測定日時"], ...
    ["mark", "MarkNo.", "Mark番号"]});
names = string({base.name});
shotIndex = find(names == "shotNo");
columns = [extra(1:4), base(1:shotIndex), extra(5), base(shotIndex + 1:end)];
end
