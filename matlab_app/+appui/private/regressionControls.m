function regression = regressionControls(parent, onSetting)
%REGRESSIONCONTROLS 「③ 回帰」の欄：X・Y の行に、損失関数・Huber の c・正則化・λ・かける次数を並べる（「7.」「8.」で共通）。
%   regression：画面の部品（loss・huber・regularization・lambda は [X, Y]、orders は 2 × 次数の数）と格子 grid。
MAX_PENALTY_ORDER = 6;   % 正則化をかけられる次数の上限（alignest.highOrderOptions と同じ）
axisNames = ["X", "Y"];
grid = uigridlayout(parent, [3, 6], 'ColumnWidth', {'fit', '1x', 58, '0.8x', 58, 'fit'}, ...
    'RowHeight', {'fit', 'fit', 'fit'}, 'Padding', 0, 'RowSpacing', 3, 'ColumnSpacing', 6);
title_ = label(grid, '③ 回帰', 1, [1, 2]);
title_.FontWeight = 'bold';
label(grid, 'c', 1, 3);
label(grid, '正則化', 1, 4);
label(grid, 'λ', 1, 5);
label(grid, 'かける次数', 1, 6);
[loss, huber, regularization, lambda] = deal(gobjects(1, 2));
orders = gobjects(2, MAX_PENALTY_ORDER);
for a = 1:2
    label(grid, axisNames(a), 1 + a, 1);
    loss(a) = uidropdown(grid, 'Items', {'OLS', 'Huber', 'LAD'}, 'ItemsData', {'ols', 'huber', 'lad'}, ...
        'ValueChangedFcn', onSetting, 'Tooltip', ['Huber・LAD：残差の大きい点（外れ値）ほど、当てはめへの影響（重み）を' ...
        '小さくして求め直します（尺度は残差の MAD × 1.4826）。影響を半分未満にした点を「外れ値とみなした点」として数えます。' ...
        '最小二乗は比べるとき用。']);
    place(loss(a), 1 + a, 2);
    huber(a) = uieditfield(grid, 'numeric', 'Limits', [0, Inf], 'LowerLimitInclusive', 'off', ...
        'ValueChangedFcn', onSetting, 'Tooltip', 'Huber の c。残差が c × 尺度 を超える点の重みを下げます（1.345 で正規分布の誤差のとき効率 95%）。');
    place(huber(a), 1 + a, 3);
    regularization(a) = uidropdown(grid, 'Items', {'なし', 'L2', 'L1'}, 'ItemsData', {'none', 'l2', 'l1'}, ...
        'ValueChangedFcn', onSetting, 'Tooltip', ['選んだ次数の項の係数に罰則をかけます（定数 k1・k2 と Wafer 成分には' ...
        'かけない）。L2：係数の二乗に罰則（係数を小さくして、点が少ない・項が似ているときのばらつきを抑える）。L1：係数の' ...
        '絶対値に罰則（効かない項の係数がちょうど 0 になり、使う項を選ぶのに近い）。']);
    place(regularization(a), 1 + a, 4);
    lambda(a) = uieditfield(grid, 'numeric', 'Limits', [0, Inf], 'ValueChangedFcn', onSetting, 'Tooltip', ...
        ['正則化の強さ λ。項（列）を平均0・標準偏差1にそろえた係数にかけます。L2 は過去のシミュレーション（7×11点）の' ...
        '標準が 0.1（点を減らすときは λ × √(77 / 点の数) が目安）。L1 は、そろえた係数でこの値 [nm] より効かない項が' ...
        ' 0 になる目安です。']);
    place(lambda(a), 1 + a, 5);
    orderGrid = uigridlayout(grid, [1, MAX_PENALTY_ORDER], 'ColumnWidth', repmat({'fit'}, 1, MAX_PENALTY_ORDER), ...
        'Padding', 0, 'ColumnSpacing', 2);
    place(orderGrid, 1 + a, 6);
    for order = 1:MAX_PENALTY_ORDER
        orders(a, order) = uicheckbox(orderGrid, 'Text', sprintf('%d', order), 'ValueChangedFcn', onSetting, ...
            'Tooltip', sprintf(['%d次の項（x・y のべきの和が %d の項）に正則化をかけます（初期値は2次以上。1次は k3〜k6 の' ...
            '倍率・回転）。'], order, order));
    end
end
regression = struct("grid", grid, "loss", loss, "huber", huber, "regularization", regularization, "lambda", lambda, ...
    "orders", orders);
end
