function dropdown = varianceQuantityDropdown(parent, callback)
% ばらつき分解の「縦軸」の選択：段ごとの 3σ（既定）か、分散の積み上げ（表の数値も同じものにする）
dropdown = uidropdown(parent, 'Items', {'3σ', '分散'}, 'ItemsData', {'sigma3', 'variance'}, 'Value', 'sigma3', ...
    'ValueChangedFcn', callback, 'Tooltip', ['上の図と表の数値。3σ：段ごとの 3σ = 3√（段の分散）と全体の 3σ を並べる' ...
    '（3σ は足しても全体の 3σ にならないので積み上げない）。分散：段の分散の積み上げ（足すと全体の分散）。' ...
    '下の割合の図は、どちらも分散の割合です。']);
end
